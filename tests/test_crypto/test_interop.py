"""Cross-language interop tests — verify Python SDK produces/consumes
identical wire format as TypeScript rine-core.

Test vectors generated by rine-core via tests/fixtures/generate_vectors.mjs.
"""

from __future__ import annotations

import json
import uuid
from pathlib import Path

import pytest

from rine._crypto.envelope import decode_envelope, encode_envelope
from rine._crypto.hpke import open as hpke_open
from rine._crypto.keys import (
    generate_encryption_keypair,
    generate_signing_keypair,
    jwk_to_public_key,
    signing_public_key_to_jwk,
)
from rine._crypto.sender_keys import derive_message_key, open_group, SenderKeyState
from rine._crypto.sign import sign_payload, verify_signature
from rine._utils import from_base64url, to_base64url

FIXTURES = Path(__file__).parent.parent / "fixtures" / "vectors.json"


@pytest.fixture(scope="module")
def vectors():
    """Load cross-language test vectors."""
    with open(FIXTURES) as f:
        return json.load(f)


class TestSigningInterop:
    """Ed25519 signatures from TypeScript verify in Python."""

    def test_ts_signature_verifies_in_python(self, vectors):
        v = vectors["signing"]
        pub = from_base64url(v["public_key"])
        msg = from_base64url(v["message"])
        sig = from_base64url(v["signature"])
        assert verify_signature(pub, msg, sig)

    def test_python_signature_verifies_with_ts_key(self, vectors):
        v = vectors["signing"]
        priv = from_base64url(v["private_key"])
        pub = from_base64url(v["public_key"])
        msg = b"python-generated message"
        sig = sign_payload(priv, msg)
        assert verify_signature(pub, msg, sig)
        assert len(sig) == 64


class TestEnvelopeInterop:
    """Envelopes encoded in TypeScript decode in Python and vice versa."""

    def test_ts_envelope_decodes_in_python(self, vectors):
        v = vectors["envelope"]
        encoded = from_base64url(v["encoded"])
        decoded = decode_envelope(encoded)
        assert decoded.kid == v["kid"]
        assert decoded.signature == from_base64url(v["signature"])
        assert decoded.payload == from_base64url(v["payload"])

    def test_python_envelope_matches_ts_format(self, vectors):
        v = vectors["envelope"]
        sig = from_base64url(v["signature"])
        payload = from_base64url(v["payload"])
        encoded = encode_envelope(v["kid"], sig, payload)
        assert to_base64url(encoded) == v["encoded"]


class TestHPKEInterop:
    """HPKE ciphertext from TypeScript decrypts in Python."""

    def test_ts_hpke_decrypts_in_python(self, vectors):
        v = vectors["hpke"]
        priv = from_base64url(v["recipient_private_key"])
        ct = from_base64url(v["ciphertext"])
        expected = from_base64url(v["plaintext"])
        result = hpke_open(priv, ct)
        assert result == expected

    def test_wire_format_version(self, vectors):
        v = vectors["hpke"]
        ct = from_base64url(v["ciphertext"])
        assert ct[0] == 0x01  # VERSION_HPKE

    def test_wire_format_ephemeral_key_size(self, vectors):
        v = vectors["hpke"]
        ct = from_base64url(v["ciphertext"])
        # version (1) + ephemeral pk (32) + ciphertext
        assert len(ct) > 33


class TestSenderKeysInterop:
    """Sender key derivation matches TypeScript."""

    def test_derive_message_key_matches_ts(self, vectors):
        v = vectors["sender_keys"]
        chain_key = from_base64url(v["chain_key"])
        mk, nck = derive_message_key(chain_key)
        assert to_base64url(mk) == v["message_key"]
        assert to_base64url(nck) == v["next_chain_key"]

    def test_ts_group_message_decrypts_in_python(self, vectors):
        v = vectors["sender_keys"]
        # Reconstruct sender key state from known values
        chain_key = from_base64url(v["chain_key"])
        state = SenderKeyState(
            sender_key_id=v["sender_key_id"],
            group_id=v["group_id"],
            sender_agent_id=v["agent_id"],
            chain_key=chain_key,
            message_index=0,
        )
        ct = from_base64url(v["ciphertext"])
        states = {state.sender_key_id: state}
        inner, skid, idx, updated = open_group(states, ct)
        decoded = decode_envelope(inner)
        assert decoded.payload == from_base64url(v["plaintext"])
        assert idx == 0
        assert updated.message_index == v["message_index_after"]

    def test_wire_format_version(self, vectors):
        v = vectors["sender_keys"]
        ct = from_base64url(v["ciphertext"])
        assert ct[0] == 0x02  # VERSION_SENDER_KEY


class TestUUIDInterop:
    """UUID binary conversion matches TypeScript."""

    def test_uuid_to_bytes_matches_ts(self, vectors):
        v = vectors["uuid"]
        py_bytes = uuid.UUID(v["string"]).bytes
        assert to_base64url(py_bytes) == v["bytes"]

    def test_bytes_to_uuid_matches_ts(self, vectors):
        v = vectors["uuid"]
        raw = from_base64url(v["bytes"])
        py_uuid = str(uuid.UUID(bytes=raw))
        assert py_uuid == v["roundtrip"]


class TestKeySerializationInterop:
    """Base64url key encoding matches TypeScript."""

    def test_signing_key_round_trip(self, vectors):
        v = vectors["key_serialization"]
        pub_bytes = from_base64url(v["signing_public"])
        jwk = signing_public_key_to_jwk(pub_bytes)
        recovered = jwk_to_public_key(jwk)
        assert recovered == pub_bytes
        assert to_base64url(recovered) == v["signing_public"]

    def test_key_sizes(self, vectors):
        v = vectors["key_serialization"]
        assert len(from_base64url(v["signing_private"])) == 32
        assert len(from_base64url(v["signing_public"])) == 32
        assert len(from_base64url(v["encryption_private"])) == 32
        assert len(from_base64url(v["encryption_public"])) == 32
